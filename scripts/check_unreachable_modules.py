#!/usr/bin/env python3
"""Flag UNREACHABLE modules — ``.py`` files that no other module imports and that are not a
legitimate entry point.

Why this exists (and why vulture does not cover it): vulture analyses *symbols within a file* and
treats a module's public functions as potentially-used, so a module whose functions only call each
other (internally consistent) but which is NEVER imported anywhere passes vulture clean. That is
exactly the P1.1 failure mode — ``ecs_modules/s3_sync.py`` + ``aws_networking.py`` (931 LOC) sat
dead, drifting from their live equivalents, undetected. This check does the import-graph
reachability vulture can't: build the set of imported module paths across the repo, then flag any
scoped module that is imported by nobody and is not an allowed entry point.

Scope: src/, ecs_modules/, lambda_handlers/ (configurable below). Entry points that are legitimately
never-imported (run as scripts / invoked by AWS) are allowlisted:
  * top-level phase/orchestrator scripts and Lambda handlers (invoked by name, not imported),
  * ``__init__`` / ``__main__`` modules,
  * anything matching _ALLOW (explicit allowlist for dynamic-dispatch / framework entry modules).

Exit 0 = clean; exit 1 = at least one unreachable module (prints each). Deterministic; no network.

Known limitations (the repo satisfies all three today; revisit if the import style changes):
  * Assumes ABSOLUTE imports — a module reachable ONLY via a relative import (``from . import x``)
    is not resolved to its package path and could be mis-flagged. The scoped tree currently uses
    absolute imports exclusively.
  * Only .py files are scanned for references — a module that is ONLY a ``python -m pkg.mod`` CLI
    entry named in a .sh/.yaml/doc (never imported, no ``__main__.py``) could be mis-flagged. No
    such module exists in scope today (every ``python -m``'d module is also imported).
  * The ``lambda_handlers.*`` allowlist is a whole-dir prefix, so a genuinely-dead NON-handler
    helper under lambda_handlers/ would be missed (a false-negative, the safe direction).
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

# Directories whose modules MUST be reachable (imported somewhere) unless entry-point/allowlisted.
_SCOPE_DIRS = ("src", "ecs_modules", "lambda_handlers")

# Modules that are legitimately never imported (run as a program or invoked by the platform).
# Keep this SMALL and justified — each entry is a hole in the check.
_ALLOW = {
    # Lambda handlers are invoked by AWS by module path, not imported by our code.
    "lambda_handlers",  # prefix: any lambda_handlers/<handler>.py with a `handler`/`lambda_handler`
    # ECS entrypoint submodule that is imported dynamically/started as a server is covered by the
    # import scan (container_status IS imported); nothing else in ecs_modules is exempt.
    # Auto-generated TypedDict stub module ("DO NOT EDIT - Generated by generate_type_stubs.py"):
    # a build artifact that documents the schemas; intentionally not imported by runtime code.
    "src.types",
}


def _module_key(path: Path) -> str:
    """Dotted module path relative to the repo root, e.g. src/utils/geo.py -> src.utils.geo."""
    rel = path.relative_to(REPO).with_suffix("")
    return ".".join(rel.parts)


def _iter_py() -> list[Path]:
    files: list[Path] = []
    for d in _SCOPE_DIRS:
        base = REPO / d
        if base.exists():
            files.extend(p for p in base.rglob("*.py") if "__pycache__" not in p.parts)
    return files


def _all_py_everywhere() -> list[Path]:
    """Every .py in the repo (to scan imports FROM tests/scripts/entrypoints too), excluding venvs
    and caches."""
    skip = {".venv", "venv", "__pycache__", ".git", "build", "dist", ".mypy_cache"}
    return [
        p for p in REPO.rglob("*.py") if not (set(p.relative_to(REPO).parts) & skip)
    ]


def _imported_module_keys() -> set[str]:
    """Collect the dotted paths referenced by every ``import`` / ``from ... import`` + any dynamic
    ``import_module("...")`` / ``__import__("...")`` string literal, across the WHOLE repo.
    """
    keys: set[str] = set()
    for path in _all_py_everywhere():
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except (SyntaxError, OSError):
            continue
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for a in node.names:
                    keys.add(a.name)
            elif isinstance(node, ast.ImportFrom):
                mod = node.module or ""
                keys.add(mod)
                for a in node.names:  # from pkg import submodule
                    keys.add(f"{mod}.{a.name}" if mod else a.name)
            elif isinstance(node, ast.Call):
                fn = node.func
                name = getattr(fn, "attr", None) or getattr(fn, "id", None)
                if name in ("import_module", "__import__") and node.args:
                    arg0 = node.args[0]
                    if isinstance(arg0, ast.Constant) and isinstance(arg0.value, str):
                        keys.add(arg0.value)
            elif isinstance(node, ast.Constant) and isinstance(node.value, str):
                # String-literal dotted module references: patch("src.utils.x.fn"),
                # monkeypatch.setattr("pkg.mod.attr", ...), etc. Register every dotted PREFIX so a
                # module referenced only by a test's patch target counts as reachable (exercised).
                s = node.value
                if (
                    "." in s
                    and " " not in s
                    and "/" not in s
                    and all(part.isidentifier() for part in s.split("."))
                ):
                    parts = s.split(".")
                    for i in range(2, len(parts) + 1):
                        keys.add(".".join(parts[:i]))
    return keys


def _is_entry_point(path: Path, key: str) -> bool:
    """A module that is legitimately never imported (program / platform entry point)."""
    name = path.name
    if name in ("__init__.py", "__main__.py"):
        return True
    if key in _ALLOW or any(key.startswith(p + ".") or key == p for p in _ALLOW):
        return True
    # Lambda handler: a lambda_handlers/*.py exposing a handler entry fn.
    if key.startswith("lambda_handlers."):
        return True
    return False


def main() -> int:
    imported = _imported_module_keys()
    unreachable: list[str] = []
    for path in _iter_py():
        key = _module_key(path)
        if _is_entry_point(path, key):
            continue
        # Reachable if this module key, or any parent package prefix of it, is imported, or if a
        # submodule import references it (key is a prefix of an imported dotted path).
        if key in imported:
            continue
        if any(imp == key or imp.startswith(key + ".") for imp in imported):
            continue
        # Also reachable if imported by bare leaf (from pkg import leaf) — covered above via the
        # f"{mod}.{a.name}" collection.
        unreachable.append(key)

    if unreachable:
        sys.stderr.write(
            "UNREACHABLE module(s) — imported by nobody and not an entry point "
            "(dead code like the P1.1 ecs_modules class):\n"
        )
        for k in sorted(unreachable):
            sys.stderr.write(f"  - {k.replace('.', '/')}.py\n")
        sys.stderr.write(
            "If a module is a legitimate entry point, add it to _ALLOW in "
            "scripts/check_unreachable_modules.py with a reason; otherwise delete it.\n"
        )
        return 1
    print("reachability: all scoped modules are imported or allowlisted entry points")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
